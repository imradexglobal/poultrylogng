// WhatsApp Daily Report Generator
// Formats poultry farm daily summary according to standard Nigerian poultry specifications.
// Compatible with WhatsApp Click-to-Chat: https://wa.me/?text=ENCODED_MESSAGE

export interface WhatsAppReportData {
  farmName: string;
  dateStr: string; // YYYY-MM-DD
  crateCapacity?: number;
  collections: Array<{
    session: string;
    time?: string;
    crates: number;
    pieces: number;
    totalPieces: number;
    cracked: number;
    damaged: number;
    goodEggs: number;
  }>;
  mortalityTotal?: number;
  feedKgTotal?: number;
  notes?: string;
}

/**
 * Formats date into readable string, e.g., "30 October 2026"
 */
export function formatReportDate(dateStr: string): string {
  try {
    const [year, month, day] = dateStr.split('-').map(Number);
    const d = new Date(year, month - 1, day);
    return d.toLocaleDateString('en-NG', { day: 'numeric', month: 'long', year: 'numeric' });
  } catch {
    return dateStr;
  }
}

/**
 * Generates formatted WhatsApp text for exactly one day of egg production.
 */
export function generateWhatsAppDailyReportText(data: WhatsAppReportData): string {
  const cap = data.crateCapacity || 30;
  const collections = data.collections || [];

  // Calculate cumulative daily totals
  const totalCrates = collections.reduce((s, c) => s + c.crates, 0);
  const totalExtraPieces = collections.reduce((s, c) => s + c.pieces, 0);
  const totalCollectedEggs = collections.reduce((s, c) => s + c.totalPieces, 0);
  const totalCracked = collections.reduce((s, c) => s + c.cracked, 0);
  const totalDamaged = collections.reduce((s, c) => s + c.damaged, 0);
  const totalGoodEggs = Math.max(0, totalCollectedEggs - totalCracked - totalDamaged);

  // Normalized display crates and pieces
  const normalizedCrates = Math.floor(totalCollectedEggs / cap);
  const normalizedPieces = totalCollectedEggs % cap;

  const lines: string[] = [];

  lines.push('🐔 *POULTRY FARM DAILY REPORT*');
  lines.push('');
  lines.push(`📅 *Date:* ${formatReportDate(data.dateStr)}`);
  lines.push('');
  lines.push('🥚 *EGG PRODUCTION SUMMARY*');
  lines.push('');
  lines.push(`📦 *Full Crates:* ${normalizedCrates}   🥚 *Extra Pieces:* ${normalizedPieces}`);
  lines.push('');
  lines.push(`📊 *TOTAL PRODUCTION:* ${totalCollectedEggs.toLocaleString()} Eggs`);
  lines.push('');
  lines.push(`✅ *Good/Sellable Eggs:* ${totalGoodEggs.toLocaleString()}`);
  lines.push(`⚠️ *Cracked Eggs:* ${totalCracked.toLocaleString()}`);
  lines.push(`❌ *Damaged Eggs:* ${totalDamaged.toLocaleString()}`);
  lines.push('');

  if (collections.length > 0) {
    lines.push('📝 *COLLECTION SUMMARY*');
    collections.forEach(c => {
      const timeStr = c.time ? ` (${c.time})` : '';
      lines.push(`• *${c.session}${timeStr}:* ${c.crates} crate${c.crates !== 1 ? 's' : ''} + ${c.pieces} piece${c.pieces !== 1 ? 's' : ''} (${c.totalPieces} eggs)`);
    });
    lines.push('');
  }

  lines.push(`📈 *Collection Sessions:* ${collections.length}`);

  if (typeof data.mortalityTotal === 'number' && data.mortalityTotal > 0) {
    lines.push(`☠️ *Mortality:* ${data.mortalityTotal} bird${data.mortalityTotal !== 1 ? 's' : ''}`);
  }

  if (typeof data.feedKgTotal === 'number' && data.feedKgTotal > 0) {
    const bags = (data.feedKgTotal / 25).toFixed(1);
    lines.push(`🌾 *Feed Consumed:* ${data.feedKgTotal.toFixed(1)} kg (${bags} bags)`);
  }

  if (data.notes && data.notes.trim()) {
    lines.push('');
    lines.push(`📌 *Notes:* ${data.notes.trim()}`);
  }

  lines.push('');
  lines.push('━━━━━━━━━━━━━━━━━━━━');
  lines.push(`Generated by ${data.farmName || 'PoultryLog NG'}`);
  lines.push('━━━━━━━━━━━━━━━━━━━━');

  return lines.join('\n');
}

/**
 * Builds the wa.me Click-to-Chat URL.
 * https://wa.me/?text=ENCODED_MESSAGE
 */
export function buildWhatsAppShareUrl(text: string): string {
  return `https://wa.me/?text=${encodeURIComponent(text)}`;
}

/**
 * Opens WhatsApp or WhatsApp Web in a new tab/window.
 */
export function openWhatsAppShare(text: string): void {
  const url = buildWhatsAppShareUrl(text);
  window.open(url, '_blank', 'noopener,noreferrer');
}
